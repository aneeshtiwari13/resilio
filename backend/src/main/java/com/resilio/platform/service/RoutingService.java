package com.resilio.platform.service;

import org.slf4j.Logger;
import org.slf4j.LoggerFactory;
import org.springframework.beans.factory.annotation.Value;
import org.springframework.stereotype.Service;

import java.io.File;
import java.io.FileWriter;
import java.io.IOException;
import java.nio.file.Files;
import java.nio.file.Path;
import java.nio.file.Paths;
import java.util.concurrent.atomic.AtomicReference;

@Service
public class RoutingService {

    private static final Logger log = LoggerFactory.getLogger(RoutingService.class);

    private final AtomicReference<String> activeSlot = new AtomicReference<>("BLUE");

    @Value("${resilio.nginx.config-dir:deploy/nginx}")
    private String nginxConfigDir;

    public String getActiveSlot() {
        return activeSlot.get();
    }

    public String getInactiveSlot() {
        return "BLUE".equalsIgnoreCase(activeSlot.get()) ? "GREEN" : "BLUE";
    }

    /**
     * Atomically generates and applies Nginx upstream configuration for target slot.
     */
    public synchronized boolean switchUpstreamTraffic(String targetSlot) {
        log.info("RoutingService: Switching Nginx traffic from {} -> {}", activeSlot.get(), targetSlot);

        String slotUpper = targetSlot.toUpperCase();
        if (!"BLUE".equals(slotUpper) && !"GREEN".equals(slotUpper)) {
            log.error("Invalid target slot: {}", targetSlot);
            return false;
        }

        // Hostnames within Docker network or local ports
        String targetHost = "BLUE".equals(slotUpper) ? "demo-app-blue:8080" : "demo-app-green:8080";
        String localHost = "BLUE".equals(slotUpper) ? "localhost:8081" : "localhost:8082";

        Path dirPath = Paths.get(nginxConfigDir);
        try {
            if (!Files.exists(dirPath)) {
                Files.createDirectories(dirPath);
            }

            File tempFile = new File(dirPath.toFile(), "upstream.conf.tmp");
            File targetFile = new File(dirPath.toFile(), "upstream.conf");

            // Write atomic temporary file first
            try (FileWriter writer = new FileWriter(tempFile)) {
                writer.write("# Auto-generated by Resilio RoutingService\n");
                writer.write("# Active Target Slot: " + slotUpper + "\n");
                writer.write("upstream target_backend {\n");
                writer.write("    server " + targetHost + " max_fails=3 fail_timeout=10s;\n");
                writer.write("    # Local dev fallback:\n");
                writer.write("    # server " + localHost + ";\n");
                writer.write("}\n");
            }

            // Atomic file replace / rename
            if (targetFile.exists()) {
                targetFile.delete();
            }
            boolean renamed = tempFile.renameTo(targetFile);
            if (!renamed) {
                // Fallback copy if renameTo fails across file systems
                Files.copy(tempFile.toPath(), targetFile.toPath());
                tempFile.delete();
            }

            activeSlot.set(slotUpper);
            log.info("RoutingService: Successfully applied upstream configuration for slot: {}", slotUpper);
            return true;
        } catch (IOException e) {
            log.error("RoutingService: Failed to update upstream configuration: {}", e.getMessage(), e);
            return false;
        }
    }

    /**
     * Reconciles current active slot from existing upstream.conf on disk upon startup.
     */
    public void reconcileFromDisk() {
        Path targetPath = Paths.get(nginxConfigDir, "upstream.conf");
        if (Files.exists(targetPath)) {
            try {
                String content = Files.readString(targetPath);
                if (content.contains("demo-app-green") || content.contains(":8082")) {
                    activeSlot.set("GREEN");
                } else {
                    activeSlot.set("BLUE");
                }
                log.info("RoutingService: Reconciled active slot from disk configuration: {}", activeSlot.get());
            } catch (IOException e) {
                log.warn("RoutingService: Unable to read upstream.conf on disk. Defaulting to BLUE.");
                activeSlot.set("BLUE");
            }
        }
    }
}
